import {
  AlignmentType,
  BorderStyle,
  Document,
  Footer,
  HeadingLevel,
  PageNumber,
  Packer,
  Paragraph,
  TextRun,
} from "docx";

import type { Manuscript, ManuscriptSection, Notebook } from "@/db/schema";
import { FULL_MANUSCRIPT } from "@/lib/guideline";
import { countWords } from "@/lib/utils";

const INK = "111827";
const MUTED = "6B7280";
const RULE = "D1D5DB";

/** 12pt Times New Roman at 1.5 line spacing — the usual thesis house style. */
const BODY = { font: "Times New Roman", size: 24, color: INK };

/** Each stored line becomes a paragraph; `- ` lines become bullets. */
function contentParagraphs(content: string): Paragraph[] {
  const lines = content
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  if (lines.length === 0) {
    return [new Paragraph({ children: [new TextRun({ text: "Not yet written.", italics: true, color: MUTED })] })];
  }

  return lines.map((line) => {
    const bullet = line.match(/^[-*\u2022]\s+(.*)$/);
    if (bullet) return new Paragraph({ text: bullet[1], bullet: { level: 0 } });
    return new Paragraph({ text: line });
  });
}

function muted(text: string, options: { size?: number; italics?: boolean } = {}): TextRun {
  return new TextRun({ text, size: options.size ?? 20, italics: options.italics ?? false, color: MUTED });
}

export type ManuscriptDocumentInput = {
  manuscript: Manuscript;
  notebook: Pick<Notebook, "title" | "researchArea">;
  sections: ManuscriptSection[];
  words: number;
};

/**
 * The whole manuscript as a submission-ready Word document: title, the facts a
 * supervisor looks for first, then every section as a real Heading 1 so Word's
 * navigation pane and any "insert table of contents" both work.
 */
export async function buildManuscriptDocx(input: ManuscriptDocumentInput): Promise<Buffer> {
  const { manuscript, notebook, sections, words } = input;

  const facts = [
    `${manuscript.kind} template · ${manuscript.studyType} study · ${manuscript.researchType} research`,
    notebook.researchArea ? `Research area: ${notebook.researchArea}` : null,
    manuscript.targetJournal ? `Target journal: ${manuscript.targetJournal}` : null,
    `Status: ${manuscript.status} · ${words} words (guideline target ${FULL_MANUSCRIPT.wordMin}-${FULL_MANUSCRIPT.wordMax})`,
    `Exported ${new Date().toISOString().slice(0, 10)}`,
  ].filter((line): line is string => Boolean(line));

  const children: Paragraph[] = [
    new Paragraph({ text: manuscript.title, heading: HeadingLevel.TITLE }),
    ...facts.map((line) => new Paragraph({ children: [muted(line)], spacing: { after: 40 } })),
  ];

  for (const section of sections) {
    const sectionWords = countWords(section.content);
    const budget =
      section.wordMax > 0
        ? `${sectionWords} of ${section.wordMin}-${section.wordMax} words · ${section.status}`
        : `${sectionWords} words · ${section.status}`;

    children.push(
      new Paragraph({
        text: section.heading,
        heading: HeadingLevel.HEADING_1,
        spacing: { before: 320, after: 60 },
      }),
      new Paragraph({ children: [muted(budget, { size: 18, italics: true })], spacing: { after: 160 } }),
      ...contentParagraphs(section.content),
    );
  }

  children.push(
    new Paragraph({
      border: { top: { style: BorderStyle.SINGLE, size: 6, color: RULE, space: 8 } },
      spacing: { before: 400 },
      children: [
        muted(
          `Generated by Kadi Research Studio from the notebook "${notebook.title}". Every AI-drafted paragraph must be verified against its source before submission.`,
          { size: 18, italics: true },
        ),
      ],
    }),
  );

  const document = new Document({
    creator: "Kadi Research Studio",
    title: manuscript.title,
    description: `Manuscript exported from the notebook "${notebook.title}"`,
    styles: {
      default: {
        document: {
          run: BODY,
          paragraph: { spacing: { line: 360, after: 160 } },
        },
        title: {
          run: { ...BODY, size: 36, bold: true },
          paragraph: { spacing: { after: 160 } },
        },
        heading1: {
          run: { ...BODY, size: 28, bold: true },
          paragraph: { keepNext: true },
        },
      },
    },
    sections: [
      {
        properties: {
          page: { margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } },
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  muted(`${manuscript.title} — `, { size: 18 }),
                  new TextRun({ children: [PageNumber.CURRENT], size: 18, color: MUTED }),
                ],
              }),
            ],
          }),
        },
        children,
      },
    ],
  });

  return Packer.toBuffer(document);
}
