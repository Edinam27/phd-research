import { fail, toErrorResponse } from "@/lib/api";
import { getCurrentUser } from "@/lib/auth";
import { loadManuscriptContext, loadSections, manuscriptWordCount } from "@/lib/manuscripts";
import { FULL_MANUSCRIPT } from "@/lib/guideline";
import { countWords } from "@/lib/utils";

export const runtime = "nodejs";

type Params = { params: Promise<{ id: string }> };

function slug(value: string): string {
  return (
    value
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "")
      .slice(0, 60) || "manuscript"
  );
}

/** Assembles every written section into one submission-ready document. */
export async function GET(request: Request, { params }: Params) {
  try {
    const user = await getCurrentUser();
    if (!user) return fail("Sign in to continue.", 401);

    const { id } = await params;
    const { manuscript, notebook } = await loadManuscriptContext(id, user.id);
    const sections = await loadSections(id);

    const format = (new URL(request.url).searchParams.get("format") ?? "md").toLowerCase();
    const words = manuscriptWordCount(sections);

    if (format === "json") {
      return new Response(
        JSON.stringify(
          {
            manuscript,
            notebook: { title: notebook.title, researchArea: notebook.researchArea },
            wordCount: words,
            sections: sections.map((section) => ({
              key: section.sectionKey,
              heading: section.heading,
              status: section.status,
              words: countWords(section.content),
              content: section.content,
            })),
          },
          null,
          2,
        ),
        {
          headers: {
            "Content-Type": "application/json",
            "Content-Disposition": `attachment; filename="${slug(manuscript.title)}.json"`,
          },
        },
      );
    }

    const header = [
      `# ${manuscript.title}`,
      "",
      `**Template:** ${manuscript.kind} · **Design:** ${manuscript.studyType}`,
      manuscript.targetJournal ? `**Target journal:** ${manuscript.targetJournal}` : null,
      `**Status:** ${manuscript.status} · **Word count:** ${words} (guideline target ${FULL_MANUSCRIPT.wordMin}-${FULL_MANUSCRIPT.wordMax})`,
      "",
      "---",
      "",
    ]
      .filter((line): line is string => line !== null)
      .join("\n");

    const body = sections
      .map((section) => {
        const sectionWords = countWords(section.content);
        const budget =
          section.wordMax > 0 ? `${sectionWords}/${section.wordMin}-${section.wordMax} words` : `${sectionWords} words`;
        return [`## ${section.heading}`, "", `*${budget} · ${section.status}*`, "", section.content.trim() || "*(not yet written)*", ""].join("\n");
      })
      .join("\n");

    const footer = [
      "",
      "---",
      "",
      `*Generated by PhD Research Studio from notebook "${notebook.title}". Every AI-drafted paragraph must be verified against its source before submission.*`,
    ].join("\n");

    const markdown = `${header}${body}${footer}`;

    if (format === "txt") {
      const plain = markdown
        .replace(/^#{1,6}\s+/gm, "")
        .replace(/\*\*(.+?)\*\*/g, "$1")
        .replace(/\*(.+?)\*/g, "$1");
      return new Response(plain, {
        headers: {
          "Content-Type": "text/plain; charset=utf-8",
          "Content-Disposition": `attachment; filename="${slug(manuscript.title)}.txt"`,
        },
      });
    }

    return new Response(markdown, {
      headers: {
        "Content-Type": "text/markdown; charset=utf-8",
        "Content-Disposition": `attachment; filename="${slug(manuscript.title)}.md"`,
      },
    });
  } catch (error) {
    return toErrorResponse(error);
  }
}
